export function buildPrompt(payload) {
  const {
    factText = "",
    audience = "",
    situation = "",
    goal = "",
    tone = "",
    language = ""
  } = payload;

  return `
Ты помогаешь подготовить короткий business small talk для встречи.

ЗАДАЧА
На основе  заданного факта и входных данных создай 3 варианта small talk. Свяжи факт и данные
Клчевая информация в поле Ситуация

ВХОДНЫЕ ДАННЫЕ
Язык: ${language || "русский"}
Тон: ${tone || "нейтральный"}
Аудитория / собеседник: ${audience || "не указано"}
Ситуация: ${situation || "не указана"}
Цель: ${goal || "не указана"}

ФАКТ
${factText || "не указан"}

ПРАВИЛА
1. Используй только данный факт.
2. Ничего не выдумывай сверх данного факта.
3. Каждый вариант должен быть коротким и естественным.
4. Каждый вариант должен звучать как готовая реплика для живого разговора.
5. Не добавляй длинные объяснения.
6. Верни ровно 3 варианта.
7. Верни только JSON.
10. Каждый вариант должен звучать как естественная фраза, которую можно сказать собеседнику.
11. Не повторяй факт дословно.
12. Добавь легкую интерпретацию или вопрос.
13. Фраза должна быть пригодна для начала разговора

Формат ответа:
{
  "variants": [
    { "id": 1, "text": "..." },
    { "id": 2, "text": "..." },
    { "id": 3, "text": "..." }
  ]
}
`.trim();
}